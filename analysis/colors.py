def usage_legend():
    """凡例表示用に(グループ名, 区分名, 色)のリストをグループ順に返す。"""
    items = [
        (_USAGE_GROUPS[label], label, color)
        for label, color in USAGE_COLOR_MAP.items()
        if label is not None
    ]
    return sorted(items, key=lambda item: _USAGE_GROUP_ORDER.index(item[0]))
